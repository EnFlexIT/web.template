import fs from "node:fs";
import path from "node:path";

function parseProperties(content) {
  const properties = {};

  for (
    const rawLine of
    content.split(/\r?\n/)
  ) {
    const line =
      rawLine.trim();

    if (
      !line ||
      line.startsWith("#") ||
      line.startsWith("!")
    ) {
      continue;
    }

    const separatorIndex =
      line.indexOf("=");

    if (
      separatorIndex < 0
    ) {
      throw new Error(
        `Invalid properties line: "${rawLine}". Expected key=value.`,
      );
    }

    const key =
      line
        .slice(
          0,
          separatorIndex,
        )
        .trim();

    const value =
      line
        .slice(
          separatorIndex + 1,
        )
        .trim();

    if (!key) {
      throw new Error(
        `Invalid properties line: "${rawLine}". Property key is empty.`,
      );
    }

    if (
      Object.hasOwn(
        properties,
        key,
      )
    ) {
      throw new Error(
        `Duplicate property key: "${key}".`,
      );
    }

    properties[key] =
      value;
  }

  return properties;
}

function requireValue(
  value,
  description,
) {
  const normalized =
    String(
      value ?? "",
    ).trim();

  if (!normalized) {
    throw new Error(
      `Missing required build metadata: ${description}.`,
    );
  }

  return normalized;
}

function optionalValue(
  value,
) {
  const normalized =
    String(
      value ?? "",
    ).trim();

  return (
    normalized ||
    undefined
  );
}

function readPackageJson(
  rootDirectory,
) {
  const packageJsonPath =
    path.join(
      rootDirectory,
      "package.json",
    );

  if (
    !fs.existsSync(
      packageJsonPath,
    )
  ) {
    throw new Error(
      `package.json does not exist: ${packageJsonPath}`,
    );
  }

  return JSON.parse(
    fs.readFileSync(
      packageJsonPath,
      "utf8",
    ),
  );
}

function readTemplateMetadata(
  rootDirectory,
) {
  const templatePropertiesPath =
    path.join(
      rootDirectory,
      "src",
      "template",
      "config",
      "template.properties",
    );

  if (
    !fs.existsSync(
      templatePropertiesPath,
    )
  ) {
    throw new Error(
      `Template metadata does not exist: ${templatePropertiesPath}`,
    );
  }

  return parseProperties(
    fs.readFileSync(
      templatePropertiesPath,
      "utf8",
    ),
  );
}

export function generateApplicationBuildInfo(
  rootDirectory,
) {
  const packageJson =
    readPackageJson(
      rootDirectory,
    );

  const templateMetadata =
    readTemplateMetadata(
      rootDirectory,
    );

  const packageName =
    requireValue(
      packageJson.name,
      "package.json name",
    );

  const packageVersion =
    requireValue(
      packageJson.version,
      "package.json version",
    );

  const templatePackageName =
    requireValue(
      templateMetadata.TemplatePackageName,
      "TemplatePackageName",
    );

  const templateVersion =
    requireValue(
      templateMetadata.TemplateVersion,
      "TemplateVersion",
    );

  const isTemplateRepository =
    packageName ===
    templatePackageName;

  /*
   * Release-specific values are injected only by
   * the real release/build pipeline.
   *
   * Normal local config generation intentionally
   * leaves them undefined. This keeps
   * `npm run config:generate` deterministic.
   */
  const applicationReleaseTag =
    optionalValue(
      process.env
        .ENFLEX_APPLICATION_RELEASE_TAG,
    );

  const buildTimestamp =
    optionalValue(
      process.env
        .ENFLEX_BUILD_TIMESTAMP,
    );

  const application = {
    packageName:
      isTemplateRepository
        ? undefined
        : packageName,

    version:
      isTemplateRepository
        ? undefined
        : packageVersion,

    releaseTag:
      isTemplateRepository
        ? undefined
        : applicationReleaseTag,
  };

  const template = {
    packageName:
      templatePackageName,

    version:
      templateVersion,
  };

  const build =
    buildTimestamp
      ? {
          timestamp:
            buildTimestamp,
        }
      : undefined;

  return {
    application,
    template,
    build,
  };
}

export function writeGeneratedApplicationBuildInfo(
  rootDirectory,
  buildInfo,
) {
  const generatedDirectory =
    path.join(
      rootDirectory,
      "src",
      "application",
      "generated",
    );

  const generatedFilePath =
    path.join(
      generatedDirectory,
      "applicationBuildInfo.generated.ts",
    );

  const generatedContent = `
// This file is generated automatically.
// Do not edit this file manually.

export const applicationBuildInfo =
${JSON.stringify(
  buildInfo,
  null,
  2,
)} as const;
`.trimStart();

  fs.mkdirSync(
    generatedDirectory,
    {
      recursive: true,
    },
  );

  fs.writeFileSync(
    generatedFilePath,
    generatedContent,
    "utf8",
  );
}