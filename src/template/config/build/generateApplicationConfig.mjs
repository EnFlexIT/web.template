import fs from "node:fs";
import path from "node:path";

const rootDirectory = process.cwd();

const propertiesPath = path.join(
  rootDirectory,
  "src",
  "application",
  "config",
  "application.properties",
);

const generatedDirectory = path.join(
  rootDirectory,
  "src",
  "application",
  "generated",
);

const generatedFilePath = path.join(
  generatedDirectory,
  "applicationConfig.generated.ts",
);

function parseProperties(content) {
  const properties = {};

  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();

    if (
      !line ||
      line.startsWith("#") ||
      line.startsWith("!")
    ) {
      continue;
    }

    const separatorIndex = line.indexOf("=");

    if (separatorIndex < 0) {
      continue;
    }

    const key = line
      .slice(0, separatorIndex)
      .trim();

    const value = line
      .slice(separatorIndex + 1)
      .trim();

    properties[key] = value;
  }

  return properties;
}

function requireProperty(properties, key) {
  const value = properties[key]?.trim();

  if (!value) {
    throw new Error(
      `Missing required application property: ${key}`,
    );
  }

  return value;
}

const fileContent =
  fs.readFileSync(propertiesPath, "utf8");

const properties =
  parseProperties(fileContent);

const applicationId =
  requireProperty(properties, "ApplicationId");

const applicationTitle =
  requireProperty(properties, "ApplicationTitle");

const generatedContent = `
// This file is generated automatically.
// Do not edit this file manually.

import type {
  ApplicationConfig,
} from "@/template/application/ApplicationConfig";

export const applicationConfig: ApplicationConfig = {
  id: ${JSON.stringify(applicationId)},
  displayName: ${JSON.stringify(applicationTitle)},

  navigation: {
    menu: {
      items: [],
      isEnabled: () => true,
    },

    tabs: {
      items: [],
      isEnabled: () => true,
    },
  },
};
`.trimStart();

fs.mkdirSync(
  generatedDirectory,
  { recursive: true },
);

fs.writeFileSync(
  generatedFilePath,
  generatedContent,
  "utf8",
);

console.log(
  `Generated application configuration for "${applicationTitle}" (${applicationId}).`,
);