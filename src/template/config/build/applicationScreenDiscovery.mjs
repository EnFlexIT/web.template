import fs from "node:fs";
import path from "node:path";

function collectTsxFiles(
  directory,
) {
  const files = [];

  for (
    const entry of
    fs.readdirSync(
      directory,
      {
        withFileTypes: true,
      },
    )
  ) {
    const absolutePath =
      path.join(
        directory,
        entry.name,
      );

    if (
      entry.isDirectory()
    ) {
      files.push(
        ...collectTsxFiles(
          absolutePath,
        ),
      );

      continue;
    }

    if (
      entry.isFile() &&
      entry.name.endsWith(
        "Screen.tsx",
      )
    ) {
      files.push(
        absolutePath,
      );
    }
  }

  return files;
}

function toRegistryKey(
  componentName,
) {
  return componentName
    .replace(
      /([a-z0-9])([A-Z])/g,
      "$1-$2",
    )
    .replace(
      /([A-Z])([A-Z][a-z])/g,
      "$1-$2",
    )
    .toLowerCase();
}

function hasNamedExport(
  content,
  componentName,
) {
  const escapedName =
    componentName.replace(
      /[.*+?^${}()|[\]\\]/g,
      "\\$&",
    );

  const patterns = [
    new RegExp(
      `export\\s+function\\s+${escapedName}\\b`,
    ),

    new RegExp(
      `export\\s+(?:const|let|var|class)\\s+${escapedName}\\b`,
    ),

    new RegExp(
      `export\\s*\\{[^}]*\\b${escapedName}\\b[^}]*\\}`,
    ),
  ];

  return patterns.some(
    (pattern) =>
      pattern.test(
        content,
      ),
  );
}

export function discoverApplicationScreens(
  rootDirectory,
) {
  const screensDirectory =
    path.join(
      rootDirectory,
      "src",
      "application",
      "screens",
    );

  if (
    !fs.existsSync(
      screensDirectory,
    )
  ) {
    return [];
  }

  const files =
    collectTsxFiles(
      screensDirectory,
    );

  const screens = [];
  const registryKeys =
    new Map();

  for (
    const filePath of files
  ) {
    const componentName =
      path.basename(
        filePath,
        ".tsx",
      );

    if (
      !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(
        componentName,
      )
    ) {
      throw new Error(
        `Invalid Application screen filename: "${componentName}.tsx".`,
      );
    }

    const content =
      fs.readFileSync(
        filePath,
        "utf8",
      );

    if (
      !hasNamedExport(
        content,
        componentName,
      )
    ) {
      throw new Error(
        [
          `Application screen "${componentName}.tsx" must export`,
          `a named component called "${componentName}".`,
        ].join(
          " ",
        ),
      );
    }

    const registryKey =
      toRegistryKey(
        componentName,
      );

    const existingFile =
      registryKeys.get(
        registryKey,
      );

    if (
      existingFile
    ) {
      throw new Error(
        [
          `Duplicate Application screen registry key "${registryKey}".`,
          `Files: "${existingFile}" and "${filePath}".`,
        ].join(
          " ",
        ),
      );
    }

    registryKeys.set(
      registryKey,
      filePath,
    );

    const relativePath =
      path
        .relative(
          screensDirectory,
          filePath,
        )
        .replace(
          /\\/g,
          "/",
        )
        .replace(
          /\.tsx$/,
          "",
        );

    screens.push({
      registryKey,
      componentName,
      importPath:
        `../screens/${relativePath}`,
    });
  }

  return screens.sort(
    (
      left,
      right,
    ) =>
      left.registryKey.localeCompare(
        right.registryKey,
      ),
  );
}

export function writeGeneratedApplicationScreenRegistry(
  rootDirectory,
  screens,
) {
  const generatedDirectory =
    path.join(
      rootDirectory,
      "src",
      "application",
      "generated",
    );

  const generatedFilePath =
    path.join(
      generatedDirectory,
      "applicationScreenRegistry.generated.ts",
    );

  const imports =
    screens
      .map(
        (screen) =>
          [
            "import {",
            `  ${screen.componentName},`,
            `} from ${JSON.stringify(screen.importPath)};`,
          ].join(
            "\n",
          ),
      )
      .join(
        "\n\n",
      );

  const entries =
    screens
      .map(
        (screen) =>
          [
            `  ${JSON.stringify(screen.registryKey)}:`,
            `    ${screen.componentName},`,
          ].join(
            "\n",
          ),
      )
      .join(
        "\n\n",
      );

  const generatedContent = `
// This file is generated automatically.
// Do not edit this file manually.

import type {
  ScreenRegistry,
} from "@template";

${imports}

export const generatedApplicationScreenRegistry:
  ScreenRegistry = {
${entries}
};
`.trimStart();

  fs.mkdirSync(
    generatedDirectory,
    {
      recursive: true,
    },
  );

  fs.writeFileSync(
    generatedFilePath,
    generatedContent,
    "utf8",
  );
}