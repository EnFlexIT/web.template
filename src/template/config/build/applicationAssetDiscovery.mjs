import fs from "node:fs";
import path from "node:path";

const supportedImageExtensions =
  new Set([
    ".png",
    ".jpg",
    ".jpeg",
    ".webp",
  ]);

function toPropertyName(
  fileName,
) {
  const nameWithoutExtension =
    path.parse(
      fileName,
    ).name;

  const parts =
    nameWithoutExtension
      .split(
        /[^A-Za-z0-9]+/,
      )
      .filter(
        Boolean,
      );

  if (
    parts.length === 0
  ) {
    throw new Error(
      `Invalid Application asset filename: "${fileName}".`,
    );
  }

  const propertyName =
    parts
      .map(
        (
          part,
          index,
        ) => {
          if (
            index === 0
          ) {
            return (
              part.charAt(0).toLowerCase() +
              part.slice(1)
            );
          }

          return (
            part.charAt(0).toUpperCase() +
            part.slice(1)
          );
        },
      )
      .join("");

  if (
    !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(
      propertyName,
    )
  ) {
    throw new Error(
      [
        `Application asset "${fileName}"`,
        `cannot be converted to a valid property name.`,
      ].join(
        " ",
      ),
    );
  }

  return propertyName;
}

export function discoverApplicationAssets(
  rootDirectory,
) {
  const assetsDirectory =
    path.join(
      rootDirectory,
      "src",
      "application",
      "assets",
    );

  if (
    !fs.existsSync(
      assetsDirectory,
    )
  ) {
    return [];
  }

  const assets = [];
  const propertyNames =
    new Map();

  for (
    const entry of
    fs.readdirSync(
      assetsDirectory,
      {
        withFileTypes: true,
      },
    )
  ) {
    if (
      !entry.isFile()
    ) {
      continue;
    }

    const extension =
      path
        .extname(
          entry.name,
        )
        .toLowerCase();

    if (
      !supportedImageExtensions.has(
        extension,
      )
    ) {
      continue;
    }

    const propertyName =
      toPropertyName(
        entry.name,
      );

    const existingFile =
      propertyNames.get(
        propertyName,
      );

    if (
      existingFile
    ) {
      throw new Error(
        [
          `Duplicate Application asset property "${propertyName}".`,
          `Files: "${existingFile}" and "${entry.name}".`,
        ].join(
          " ",
        ),
      );
    }

    propertyNames.set(
      propertyName,
      entry.name,
    );

    assets.push({
      propertyName,
      fileName:
        entry.name,
    });
  }

  return assets.sort(
    (
      left,
      right,
    ) =>
      left.propertyName.localeCompare(
        right.propertyName,
      ),
  );
}

export function writeGeneratedApplicationAssets(
  rootDirectory,
  assets,
) {
  const generatedDirectory =
    path.join(
      rootDirectory,
      "src",
      "application",
      "generated",
    );

  const generatedFilePath =
    path.join(
      generatedDirectory,
      "applicationAssets.generated.ts",
    );

  const entries =
    assets
      .map(
        (asset) =>
          [
            `  ${asset.propertyName}:`,
            `    require(${JSON.stringify(`../assets/${asset.fileName}`)}),`,
          ].join(
            "\n",
          ),
      )
      .join(
        "\n\n",
      );

  const generatedContent = `
// This file is generated automatically.
// Do not edit this file manually.

export const ApplicationImages = {
${entries}
} as const;
`.trimStart();

  fs.mkdirSync(
    generatedDirectory,
    {
      recursive: true,
    },
  );

  fs.writeFileSync(
    generatedFilePath,
    generatedContent,
    "utf8",
  );
}